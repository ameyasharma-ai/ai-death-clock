"""Data models and serialization logic for user profiles and lifespan estimates.

Defines schemas for demographic, geographic, and lifestyle factors, as well as
computed actuarial predictions returned by the Gemini AI engine.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import date, datetime, time, timezone
from pathlib import Path
from typing import Any

from config import PROFILE_PATH


@dataclass
class UserProfile:
    """Captures user demographic, geographic, and lifestyle attributes.

    Attributes:
        birth_date: Date of birth (YYYY-MM-DD).
        biological_sex: 'Male', 'Female', or 'Other'.
        country: Country of residence.
        city: City or state of residence.
        living_area: 'Urban', 'Suburban', or 'Rural'.
        air_quality: 'Clean / Mountain', 'Moderate', or 'Heavily Polluted'.
        sleep_hours: Average sleep duration per day in hours.
        sleep_quality: 'Poor', 'Moderate', or 'Excellent / Restorative'.
        exercise_frequency: 'Sedentary (None)', 'Light (1-2x/wk)', 'Moderate (3-4x/wk)', or 'Athletic (5+x/wk)'.
        diet_type: 'Standard / Processed', 'Balanced Home-cooked', 'Mediterranean', 'Vegetarian / Plant-focused', or 'Keto / Low-carb'.
        smoking_status: 'Non-smoker', 'Former smoker', 'Vaper', or 'Active smoker'.
        alcohol_units_per_week: Estimated standard drinks per week.
        caffeine_daily_cups: Cups of coffee or caffeinated drinks per day.
        stress_level: Self-reported stress on a scale of 1 to 10.
        work_nature: 'Desk / Sedentary', 'Active / Standing', or 'Intense Physical Labor'.
        social_connection: 'Isolated', 'Moderate / Some Friends', or 'Strong Family / Community Ties'.
        sense_of_purpose: 'Unclear / Searching', 'Moderate', or 'High / Clear Life Mission (Ikigai)'.
        family_longevity: 'Below average (<70)', 'Average (~70-80)', or 'Exceptional (85+ years)'.
        chronic_conditions: Any diagnosed chronic conditions or 'None'.
    """

    birth_date: str
    biological_sex: str = "Male"
    country: str = "India"
    city: str = "Pune"
    living_area: str = "Urban"
    air_quality: str = "Moderate"
    sleep_hours: float = 7.0
    sleep_quality: str = "Moderate"
    exercise_frequency: str = "Moderate (3-4x/wk)"
    diet_type: str = "Balanced Home-cooked"
    smoking_status: str = "Non-smoker"
    alcohol_units_per_week: int = 1
    caffeine_daily_cups: int = 2
    stress_level: int = 5
    work_nature: str = "Desk / Sedentary"
    social_connection: str = "Strong Family / Community Ties"
    sense_of_purpose: str = "High / Clear Life Mission (Ikigai)"
    family_longevity: str = "Exceptional (85+ years)"
    chronic_conditions: str = "None"
    personal_notes: str = ""
    custom_fields: dict[str, str] = field(default_factory=dict)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> UserProfile:
        """Safely construct UserProfile ignoring obsolete or extra fields.

        Args:
            data: Raw dictionary from serialized storage.

        Returns:
            UserProfile: Validated dataclass instance.
        """
        from dataclasses import fields
        valid_fields = {f.name for f in fields(cls)}
        filtered = {k: v for k, v in data.items() if k in valid_fields}
        return cls(**filtered)


@dataclass
class LifespanEstimate:
    """Actuarial and biogerontological prediction generated by Gemini AI.

    Attributes:
        estimated_lifespan_years: Total predicted lifespan in solar years.
        estimated_death_date: Calculated timestamp of estimated lifespan completion.
        baseline_country_expectancy: Actuarial baseline for nationality and sex.
        net_lifestyle_modifier_years: Net gain or loss in years from lifestyle and environment.
        summary: Narrative summary and architectural assessment from Gemini.
        top_boosters: Factors extending lifespan with estimated years added.
        top_risks: Factors reducing lifespan with estimated years subtracted.
        longevity_recommendations: High-leverage actionable interventions to gain additional years.
    """

    estimated_lifespan_years: float
    estimated_death_date: str
    baseline_country_expectancy: float
    net_lifestyle_modifier_years: float
    summary: str
    top_boosters: list[str] = field(default_factory=list)
    top_risks: list[str] = field(default_factory=list)
    longevity_recommendations: list[str] = field(default_factory=list)


@dataclass
class SavedState:
    """Complete application state containing profile and calculated estimates.

    Attributes:
        profile: The user questionnaire answers.
        estimate: The computed Gemini longevity estimate.
        created_at: ISO timestamp of record creation.
        updated_at: ISO timestamp of last update.
    """

    profile: UserProfile
    estimate: LifespanEstimate
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def get_birth_datetime(self) -> datetime:
        """Parse birth date into datetime with midnight UTC.

        Returns:
            datetime: Aware datetime object representing birth.
        """
        try:
            d = date.fromisoformat(self.profile.birth_date)
            return datetime.combine(d, time.min).replace(tzinfo=timezone.utc)
        except Exception:
            return datetime(1998, 1, 1, tzinfo=timezone.utc)

    def get_death_datetime(self) -> datetime:
        """Parse estimated death date into datetime object.

        Returns:
            datetime: Aware datetime object representing estimated end-of-life.
        """
        try:
            return datetime.fromisoformat(self.estimate.estimated_death_date)
        except Exception:
            # Fallback calculate from birth + years
            b = self.get_birth_datetime()
            days = self.estimate.estimated_lifespan_years * 365.2425
            from datetime import timedelta
            return b + timedelta(days=days)

    def calculate_progress(self, now: datetime | None = None) -> tuple[float, float, float, float]:
        """Calculate life progress statistics.

        Args:
            now: Current datetime or None to use datetime.now(timezone.utc).

        Returns:
            tuple[float, float, float, float]: (
                progress_percentage (0.0 - 100.0),
                total_life_seconds,
                elapsed_seconds,
                remaining_seconds
            )
        """
        if now is None:
            now = datetime.now(timezone.utc)

        birth = self.get_birth_datetime()
        death = self.get_death_datetime()

        total_seconds = max(1.0, (death - birth).total_seconds())
        elapsed_seconds = max(0.0, (now - birth).total_seconds())
        remaining_seconds = max(0.0, (death - now).total_seconds())

        progress = min(100.0, max(0.0, (elapsed_seconds / total_seconds) * 100.0))
        return progress, total_seconds, elapsed_seconds, remaining_seconds

    def to_dict(self) -> dict[str, Any]:
        """Convert state to dictionary for JSON serialization.

        Returns:
            dict[str, Any]: Serializable state dictionary.
        """
        return {
            "profile": asdict(self.profile),
            "estimate": asdict(self.estimate),
            "created_at": self.created_at,
            "updated_at": self.updated_at,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> SavedState:
        """Reconstruct state from loaded JSON dictionary.

        Args:
            data: Loaded dictionary.

        Returns:
            SavedState: Hydrated state object.
        """
        profile = UserProfile.from_dict(data["profile"])
        estimate = LifespanEstimate(**data["estimate"])
        return cls(
            profile=profile,
            estimate=estimate,
            created_at=data.get("created_at", datetime.now(timezone.utc).isoformat()),
            updated_at=data.get("updated_at", datetime.now(timezone.utc).isoformat()),
        )


def load_saved_profile(path: Path = PROFILE_PATH) -> SavedState | None:
    """Load saved state from disk if present.

    Args:
        path: Path to profile.json.

    Returns:
        SavedState | None: Reconstructed state or None if missing or corrupted.
    """
    if not path.exists():
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return SavedState.from_dict(data)
    except Exception as exc:
        print(f"Warning: Failed to load profile from {path}: {exc}")
        return None


def save_profile(state: SavedState, path: Path = PROFILE_PATH) -> bool:
    """Persist saved state to disk.

    Args:
        state: State object to serialize.
        path: Destination file path.

    Returns:
        bool: True if write succeeded, False otherwise.
    """
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        state.updated_at = datetime.now(timezone.utc).isoformat()
        with open(path, "w", encoding="utf-8") as f:
            json.dump(state.to_dict(), f, indent=2)
        return True
    except Exception as exc:
        print(f"Error: Failed to save profile to {path}: {exc}")
        return False
